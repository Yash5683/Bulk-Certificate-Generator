from datetime import date
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.pdfbase.pdfmetrics import stringWidth
from reportlab.pdfgen import canvas

OUTPUT_DIR=Path("generated_certificates"); OUTPUT_DIR.mkdir(exist_ok=True)
def _fit_font(text,max_width,preferred=34,minimum=18):
    size=preferred
    while size>minimum and stringWidth(text,"Helvetica-Bold",size)>max_width: size-=1
    return size
def generate_certificate(*,certificate_id,recipient_name,course,event_name,certificate_title,completion_date:date):
    output=OUTPUT_DIR/f"{certificate_id}.pdf"; width,height=landscape(A4); pdf=canvas.Canvas(str(output),pagesize=(width,height))
    margin=28; pdf.setStrokeColor(colors.HexColor("#1f3c88")); pdf.setLineWidth(3); pdf.rect(margin,margin,width-2*margin,height-2*margin)
    pdf.setStrokeColor(colors.HexColor("#c9a227")); pdf.setLineWidth(1); pdf.rect(margin+10,margin+10,width-2*margin-20,height-2*margin-20)
    pdf.setFillColor(colors.HexColor("#1f3c88")); pdf.setFont("Helvetica-Bold",30); pdf.drawCentredString(width/2,height-105,certificate_title.upper())
    pdf.setFillColor(colors.black); pdf.setFont("Helvetica",15); pdf.drawCentredString(width/2,height-140,"This certificate is proudly presented to")
    pdf.setFillColor(colors.HexColor("#222222")); pdf.setFont("Helvetica-Bold",_fit_font(recipient_name,width-150)); pdf.drawCentredString(width/2,height-195,recipient_name)
    pdf.setStrokeColor(colors.HexColor("#c9a227")); pdf.line(width/2-170,height-208,width/2+170,height-208)
    pdf.setFillColor(colors.black); pdf.setFont("Helvetica",14); pdf.drawCentredString(width/2,height-245,f"for successfully participating in {course}"); pdf.drawCentredString(width/2,height-270,f"as part of {event_name}")
    pdf.setFont("Helvetica",12); pdf.drawCentredString(width/2,height-305,f"Completion date: {completion_date:%d %B %Y}")
    pdf.setFont("Helvetica",11); pdf.setFillColor(colors.HexColor("#555555")); pdf.drawCentredString(width/2,70,"Generated by Bulk Certificate Generator")
    pdf.save(); return output
